from typing import Optional, Any, Dict, List
from datetime import datetime, timezone
from sqlalchemy import String, Integer, Text, DateTime, ForeignKey, JSON
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.base import Base, UUIDPrimaryKeyMixin, TimestampMixin
from app.models.enums import ExtractionStatus, ExtractionReviewStatus


class IncidentExtraction(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    Structured incident extraction generated by AI from investigation documents.
    Preserves raw AI suggestions separately from confirmed Incident records.
    Maintains 21 CFR Part 11 ALCOA+ traceability for human review and selective field acceptance.
    """

    __tablename__ = "incident_extractions"

    investigation_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("investigations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    ai_execution_id: Mapped[Optional[str]] = mapped_column(
        String(36),
        ForeignKey("ai_executions.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    created_by: Mapped[Optional[str]] = mapped_column(
        String(36),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    source_document_ids: Mapped[List[str]] = mapped_column(
        JSON,
        nullable=False,
        default=list,
    )
    provider: Mapped[str] = mapped_column(String(50), nullable=False)
    model: Mapped[str] = mapped_column(String(100), nullable=False)
    prompt_version: Mapped[str] = mapped_column(String(20), nullable=False)

    status: Mapped[str] = mapped_column(
        String(30),
        default=ExtractionStatus.PENDING.value,
        nullable=False,
        index=True,
    )
    review_status: Mapped[str] = mapped_column(
        String(30),
        default=ExtractionReviewStatus.PENDING_REVIEW.value,
        nullable=False,
        index=True,
    )

    # Structured extraction payloads with evidence provenance
    extracted_fields: Mapped[Dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        default=dict,
    )
    missing_information: Mapped[List[Any]] = mapped_column(
        JSON,
        nullable=False,
        default=list,
    )
    conflicting_information: Mapped[List[Any]] = mapped_column(
        JSON,
        nullable=False,
        default=list,
    )
    document_summaries: Mapped[List[Any]] = mapped_column(
        JSON,
        nullable=False,
        default=list,
    )

    # Human review provenance
    reviewed_by: Mapped[Optional[str]] = mapped_column(
        String(36),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    reviewed_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # Relationships
    investigation = relationship("Investigation", backref="extractions")
    ai_execution = relationship("AIExecution", backref="incident_extractions")
    creator = relationship("User", foreign_keys=[created_by], backref="created_extractions")
    reviewer = relationship("User", foreign_keys=[reviewed_by], backref="reviewed_extractions")

