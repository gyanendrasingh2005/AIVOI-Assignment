import { createSlice, PayloadAction } from '@reduxjs/toolkit';
import { User } from '@/types';

interface AuthState {
  user: User | null;
  token: string | null;
  isAuthenticated: boolean;
  isLoading: boolean;
  error: string | null;
}

// Initial demo user for testing foundation enterprise shell before full auth milestone
const initialUser: User = {
  id: 'usr_01h89qa1',
  email: 'lead.investigator@pharmagmp.com',
  fullName: 'Dr. Evelyn Vance, QA Lead',
  department: 'API Quality Assurance & Regulatory',
  role: 'QA_INVESTIGATOR',
  isActive: true,
};

const initialState: AuthState = {
  user: initialUser,
  token: localStorage.getItem('pharmarca_token') || 'demo_mock_token_for_shell',
  isAuthenticated: true,
  isLoading: false,
  error: null,
};

export const authSlice = createSlice({
  name: 'auth',
  initialState,
  reducers: {
    setUser: (state, action: PayloadAction<{ user: User; token: string }>) => {
      state.user = action.payload.user;
      state.token = action.payload.token;
      state.isAuthenticated = true;
      state.isLoading = false;
      state.error = null;
      localStorage.setItem('pharmarca_token', action.payload.token);
    },
    logout: (state) => {
      state.user = null;
      state.token = null;
      state.isAuthenticated = false;
      localStorage.removeItem('pharmarca_token');
    },
    setLoading: (state, action: PayloadAction<boolean>) => {
      state.isLoading = action.payload;
    },
    setError: (state, action: PayloadAction<string | null>) => {
      state.error = action.payload;
    },
  },
});

export const { setUser, logout, setLoading, setError } = authSlice.actions;
export default authSlice.reducer;
